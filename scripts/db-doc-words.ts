// 칼럼 이름 → 한글명 ('_yn'·'_cd'처럼 끝 낱말이 뜻을 정한다)
export function koreanName(column: string): string {
  if (column === 'id') return 'ID'
  let text = column
  for (const [re, to] of PHRASES) text = text.replace(re, to)
  return text
    .split('_')
    .map((word) => WORDS[word] ?? word)
    .join(' ')
    .replace(/ \(/g, '(')
}
